-- 01_init_schemas.sql
-- Database initialization script for Real-time Anomaly Detection Pipeline

-- 1. Create dedicated schemas to separate raw ingested data from operational analytics
CREATE SCHEMA IF NOT EXISTS raw;
CREATE SCHEMA IF NOT EXISTS ops;

-- 2. raw.trades: Stores validated incoming crypto trade events (idempotent on symbol + trade_id)
CREATE TABLE IF NOT EXISTS raw.trades (
    symbol          VARCHAR(20)     NOT NULL,
    trade_id        BIGINT          NOT NULL,
    price           NUMERIC(18, 8)  NOT NULL CHECK (price > 0),
    quantity        NUMERIC(18, 8)  NOT NULL CHECK (quantity > 0),
    trade_time_ms   BIGINT          NOT NULL,
    is_buyer_maker  BOOLEAN         NOT NULL,
    ingested_at_ms  BIGINT          NOT NULL,
    PRIMARY KEY (symbol, trade_id)
);

CREATE INDEX IF NOT EXISTS idx_trades_symbol_time ON raw.trades (symbol, trade_time_ms);

-- 3. raw.rejected_events: Dead-letter table for malformed or unparseable payloads
CREATE TABLE IF NOT EXISTS raw.rejected_events (
    id              BIGSERIAL       PRIMARY KEY,
    received_at_ms  BIGINT          NOT NULL,
    reason          TEXT            NOT NULL,
    raw_payload     JSONB           NOT NULL
);

-- 4. ops.bars: Aggregate OHLCV time bars computed from valid trades
CREATE TABLE IF NOT EXISTS ops.bars (
    symbol          VARCHAR(20)     NOT NULL,
    bar_seconds     INTEGER         NOT NULL,
    bar_start_ms    BIGINT          NOT NULL,
    open            NUMERIC(18, 8)  NOT NULL,
    high            NUMERIC(18, 8)  NOT NULL,
    low             NUMERIC(18, 8)  NOT NULL,
    close           NUMERIC(18, 8)  NOT NULL,
    volume          NUMERIC(18, 8)  NOT NULL,
    trade_count     INTEGER         NOT NULL,
    PRIMARY KEY (symbol, bar_seconds, bar_start_ms)
);

-- 5. ops.alerts: Real-time anomaly detection alerts generated by statistical and ML detectors
CREATE TABLE IF NOT EXISTS ops.alerts (
    alert_id        BIGSERIAL       PRIMARY KEY,
    symbol          VARCHAR(20)     NOT NULL,
    detector        VARCHAR(50)     NOT NULL,
    bar_start_ms    BIGINT          NOT NULL,
    bar_end_ms      BIGINT          NOT NULL,
    score           DOUBLE PRECISION NOT NULL,
    threshold       DOUBLE PRECISION NOT NULL,
    details_json    JSONB           NOT NULL,
    created_at_ms   BIGINT          NOT NULL,
    UNIQUE (symbol, detector, bar_end_ms)
);

CREATE INDEX IF NOT EXISTS idx_alerts_time ON ops.alerts (bar_end_ms);

-- 6. ops.checkpoints: Tracks operational processing offsets for incremental pipeline batches
CREATE TABLE IF NOT EXISTS ops.checkpoints (
    name            VARCHAR(50)     PRIMARY KEY,
    value           BIGINT          NOT NULL,
    updated_at_ms   BIGINT          NOT NULL
);

